SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS OrderDetails (
    OrderDetailId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    OrderId INT UNSIGNED NOT NULL,
    PackageId INT UNSIGNED NOT NULL,
    Quantity INT NOT NULL,
    UnitPrice DECIMAL(10,2) NOT NULL,
    CONSTRAINT fk_od_order FOREIGN KEY (OrderId) REFERENCES Orders(OrderId) ON DELETE CASCADE,
    CONSTRAINT fk_od_package FOREIGN KEY (PackageId) REFERENCES Packages(PackageId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;