SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS CartItems (
    CartItemId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    UserId INT UNSIGNED NULL,
    SessionId VARCHAR(100) NULL,
    PackageId INT UNSIGNED NOT NULL,
    Quantity INT NOT NULL DEFAULT 1,
    DateAdded DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cart_user FOREIGN KEY (UserId) REFERENCES Users(UserId) ON DELETE CASCADE,
    CONSTRAINT fk_cart_package FOREIGN KEY (PackageId) REFERENCES Packages(PackageId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;