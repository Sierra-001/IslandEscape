SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS Users (
    UserId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    Email VARCHAR(256) NOT NULL UNIQUE,
    PasswordHash VARCHAR(255) NOT NULL,
    FullName VARCHAR(100) NOT NULL,
    Phone VARCHAR(20) NULL,
    Role VARCHAR(20) NOT NULL DEFAULT 'Customer',
    IsActive TINYINT(1) NOT NULL DEFAULT 1,
    ResetToken VARCHAR(100) NULL,
    ResetTokenExpiry DATETIME NULL,
    CreatedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_role CHECK (Role IN ('Admin','Customer','Visitor'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS PackageCategories (
    CategoryId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    CategoryName VARCHAR(50) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS Packages (
    PackageId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    CategoryId INT UNSIGNED NOT NULL,
    Name VARCHAR(200) NOT NULL,
    Description TEXT NULL,
    Price DECIMAL(10,2) NOT NULL,
    ImageUrl VARCHAR(500) NULL,
    IsActive TINYINT(1) NOT NULL DEFAULT 1,
    CreatedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_packages_category FOREIGN KEY (CategoryId) REFERENCES PackageCategories(CategoryId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS CartItems (
    CartItemId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    UserId INT UNSIGNED NULL,
    SessionId VARCHAR(100) NULL,
    PackageId INT UNSIGNED NOT NULL,
    Quantity INT NOT NULL DEFAULT 1,
    DateAdded DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cart_user FOREIGN KEY (UserId) REFERENCES Users(UserId) ON DELETE CASCADE,
    CONSTRAINT fk_cart_package FOREIGN KEY (PackageId) REFERENCES Packages(PackageId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS Orders (
    OrderId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    UserId INT UNSIGNED NOT NULL,
    OrderDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TotalAmount DECIMAL(10,2) NOT NULL,
    PaymentStatus VARCHAR(20) NOT NULL DEFAULT 'Completed',
    DownloadCode CHAR(36) NOT NULL UNIQUE,
    CONSTRAINT fk_orders_user FOREIGN KEY (UserId) REFERENCES Users(UserId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS OrderDetails (
    OrderDetailId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    OrderId INT UNSIGNED NOT NULL,
    PackageId INT UNSIGNED NOT NULL,
    Quantity INT NOT NULL,
    UnitPrice DECIMAL(10,2) NOT NULL,
    CONSTRAINT fk_od_order FOREIGN KEY (OrderId) REFERENCES Orders(OrderId) ON DELETE CASCADE,
    CONSTRAINT fk_od_package FOREIGN KEY (PackageId) REFERENCES Packages(PackageId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ContactQueries (
    QueryId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    UserId INT UNSIGNED NULL,
    Name VARCHAR(100) NOT NULL,
    Email VARCHAR(256) NOT NULL,
    Subject VARCHAR(200) NOT NULL,
    Message TEXT NOT NULL,
    Status VARCHAR(20) NOT NULL DEFAULT 'Open',
    Response TEXT NULL,
    CreatedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_queries_user FOREIGN KEY (UserId) REFERENCES Users(UserId) ON DELETE SET NULL,
    CONSTRAINT chk_query_status CHECK (Status IN ('Open','InProgress','Resolved'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;