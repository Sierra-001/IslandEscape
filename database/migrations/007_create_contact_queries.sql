SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS ContactQueries (
    QueryId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    UserId INT UNSIGNED NULL,
    Name VARCHAR(100) NOT NULL,
    Email VARCHAR(256) NOT NULL,
    Subject VARCHAR(200) NOT NULL,
    Message TEXT NOT NULL,
    Status VARCHAR(20) NOT NULL DEFAULT 'Open',
    Response TEXT NULL,
    CreatedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_queries_user FOREIGN KEY (UserId) REFERENCES Users(UserId) ON DELETE SET NULL,
    CONSTRAINT chk_query_status CHECK (Status IN ('Open','InProgress','Resolved'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;